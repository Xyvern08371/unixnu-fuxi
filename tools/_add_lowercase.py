def add_charset(s, extra):
    """在 CHARSET 字符串字面量末尾追加字符（去重）"""
    start = s.find('CHARSET[] = "')
    if start < 0:
        return s, False
    q1 = s.find('"', start) + 1
    q2 = s.find('"', q1)
    cur = s[q1:q2]
    add = "".join(c for c in extra if c not in cur)
    return s[:q2] + add + s[q2:], True


def add_font_rows(s, chars):
    """在 FONT 表最后一个元素之后插入字形行"""
    anchor = "};"
    # 找到 FONT 数组的结束：最后一个 "0x..,0x..,0x..,0x..,0x..,0x..,0x..,0x.. },"
    pos = s.rfind("},\n};")
    if pos < 0:
        # kernel.c 的写法可能不同
        pos = s.rfind("}\n};")
    if pos < 0:
        return s, False
    end = s.find("};", pos) + 2
    rows = []
    for c in chars:
        g = LOWER_GLYPHS.get(c) or EXTRA.get(c)
        if not g:
            continue
        rows.append("  { " + ",".join("0x%02X" % b for b in g) + " }, /* %s */" % c)
    s = s[:end - 2] + "\n" + "\n".join(rows) + "\n" + s[end - 2:]
    return s, True


def process(path, chars):
    s = io.open(path, encoding="utf-8").read()
    if 'CHARSET' not in s:
        print("%s: 没有 CHARSET，跳过" % path)
        return
    s, ok1 = add_charset(s, chars)
    s, ok2 = add_font_rows(s, chars)
    io.open(path, "w", encoding="utf-8", newline="\n").write(s)
    print("%s: charset=%s font=%s" % (path, ok1, ok2))


